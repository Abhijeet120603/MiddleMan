/* USER CODE BEGIN Header_I2CSend_Task_Start */
/**
* @brief Function implementing the I2CSend_Task thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_I2CSend_Task_Start */


void I2CSend_Task_Start(void const * argument)
{
  for(;;)
  {
    memset(rx_buf, 0, RX_BUFSIZE);
    memset(tx_buf, 0, TX_BUFSIZE);

    /* Receive command from RPi */
    sig = HAL_I2C_Slave_Receive(&hi2c1, rx_buf, RX_BUFSIZE, HAL_MAX_DELAY);

    if (sig != HAL_OK)
    {
      ResetI2C(&hi2c1);
      osDelay(10);
      continue;
    }

    /* Command parsing */
    if (strcmp((char *)rx_buf, "hi") == 0)
    {
      strcpy((char *)tx_buf, "hello");
    }
    else if (strcmp((char *)rx_buf, "hi1") == 0)
    {
      strcpy((char *)tx_buf, "hi2");
    }
    else
    {
      strcpy((char *)tx_buf, "unknown");
    }

    /* Send response to RPi */
    sig = HAL_I2C_Slave_Transmit(&hi2c1, tx_buf, strlen((char *)tx_buf) + 1, HAL_MAX_DELAY);

    if (sig != HAL_OK)
    {
      ResetI2C(&hi2c1);
    }

    osDelay(10);
  }
}

